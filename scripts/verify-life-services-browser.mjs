import assert from 'node:assert/strict';
import { mkdirSync, writeFileSync } from 'node:fs';
import { chromium } from 'playwright';
const base = process.env.BASE_URL || 'http://127.0.0.1:4175';
const out = 'output/playwright/life-services';
mkdirSync(out, { recursive: true });
const browser = await chromium.launch({ headless: true, executablePath: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe' });
const checks = [], errors = [];
const context = await browser.newContext();
const page = await context.newPage();
page.on('pageerror', error => errors.push(error.message));
const ready = () => page.locator('#servicesDirectory[data-state="ready"]').waitFor();
const go = async query => { await page.goto(base + '/services' + query); await ready(); };
const layout = async label => {
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), label + ': page overflow');
  const bad = await page.locator('.service-entry, .service-view-tabs, .service-filter-fields, dialog[open]').evaluateAll(nodes => nodes.filter(n => n.scrollWidth > n.clientWidth + 2).map(n => n.className));
  assert.deepEqual(bad, [], label + ': control overflow');
  checks.push(label);
};
try {
  for (const width of [320, 390, 768, 1024, 1440]) {
    await page.setViewportSize({ width, height: 900 });
    await go('');
    assert.equal(await page.locator('#serviceCategory option').count(), 19);
    assert.equal(await page.locator('#serviceSubtopic option').count(), 107);
    assert.equal(await page.locator('.service-entry').count(), 12);
    await layout('directory-' + width);
    await page.screenshot({ path: `${out}/directory-${width}.png`, fullPage: true });
    await page.locator('.service-title-button').first().click();
    await page.locator('#serviceDetail[open]').waitFor();
    await layout('detail-' + width);
    const links = await page.locator('#serviceDetailBody a').evaluateAll(nodes => nodes.map(n => ({ href: n.href, rel: n.rel, target: n.target })));
    assert(links.length && links.every(n => n.href.startsWith('https://') && n.rel.includes('noopener') && n.target === '_blank'));
    if (width === 390) await page.screenshot({ path: `${out}/detail-390.png` });
    await page.keyboard.press('Escape');
    await page.waitForFunction(() => !document.querySelector('#serviceDetail').open && !new URLSearchParams(location.search).has('detail'));
    await ready();
    assert(await page.locator('.service-title-button').first().evaluate(n => document.activeElement === n));
  }
  await page.setViewportSize({ width: 390, height: 844 });
  await go('?q=' + encodeURIComponent('이불 세탁'));
  assert(await page.locator('.service-entry').count() > 0);
  await page.locator('.service-save').first().click(); await ready();
  await page.reload(); await ready();
  assert.equal(await page.locator('.service-save[aria-pressed="true"]').count(), 1);
  await page.locator('[data-service-view="saved"]').click(); await ready();
  assert.equal(await page.locator('.service-entry').count(), 1);
  await page.locator('.service-title-button').first().click();
  await page.locator('#serviceDetailBody .service-save').click();
  await page.keyboard.press('Escape'); await ready();
  assert.equal(await page.locator('.service-entry').count(), 0);
  checks.push('search-save-reload-remove');
  await go('');
  await page.locator('#serviceNext').click(); await ready();
  assert.equal(await page.locator('#servicePageLabel [aria-current="page"]').innerText(), '2');
  await page.goBack(); await ready();
  assert.equal(await page.locator('#servicePageLabel [aria-current="page"]').innerText(), '1');
  await page.locator('#servicePageLabel button').filter({ hasText: /^3$/ }).click(); await ready();
  assert.equal(await page.locator('#servicePageLabel [aria-current="page"]').innerText(), '3');
  checks.push('pagination-back');
  await page.locator('#serviceRegionOpen').click();
  assert.equal(await page.locator('#serviceRegionDistrict option').count(), 26);
  await page.locator('#serviceRegionDistrict').selectOption({ label: '마포구' });
  await page.locator('#serviceDongSearch').fill('연남');
  await page.locator('#serviceRegionDong').selectOption({ label: '연남동' });
  await page.locator('#serviceRememberRegion').check();
  await page.locator('#serviceRegionForm button[type="submit"]').click(); await ready();
  assert.match(await page.locator('#serviceRegionLabel').innerText(), /마포구 연남동/);
  await page.locator('[data-service-view="places"]').click(); await ready();
  assert(await page.locator('[data-place-id]').count() > 0);
  await layout('places-390');
  await page.screenshot({ path: `${out}/places-390.png`, fullPage: true });
  await page.reload(); await ready();
  assert.match(await page.locator('#serviceRegionLabel').innerText(), /마포구 연남동/);
  await page.locator('#serviceRegionOpen').click();
  await page.locator('#serviceDongType').selectOption('administrative');
  assert(await page.locator('#serviceRegionDong option').count() > 2);
  await page.keyboard.press('Escape');
  checks.push('district-dong-place-and-remember');
  await page.route('**/api/life/places?**', route => route.fulfill({ status: 503, body: '{}' }));
  await page.locator('#serviceSearch button').click();
  await page.locator('#servicesDirectory[data-state="error"]').waitFor();
  await page.unroute('**/api/life/places?**');
  await page.getByRole('button', { name: '다시 시도', exact: true }).click(); await ready();
  checks.push('api-failure-retry');
  await go('?q=zqx없는검색어');
  assert.equal(await page.locator('.service-entry').count(), 0);
  assert.match(await page.locator('#serviceFeedback').innerText(), /일치하는/);
  await page.getByRole('button', { name: '조건 초기화', exact: true }).last().click(); await ready();
  checks.push('empty-and-reset');
  await page.route('**/data/life-services.json?**', route => route.fulfill({ status: 503, body: '{}' }));
  await page.goto(base + '/services');
  await page.locator('#servicesDirectory[data-state="error"]').waitFor();
  await page.locator('#serviceReset').click();
  await page.unroute('**/data/life-services.json?**');
  await page.getByRole('button', { name: '다시 시도', exact: true }).click(); await ready();
  checks.push('directory-failure-retry-and-inert-controls');
  await page.setViewportSize({ width: 320, height: 740 });
  await page.locator('.service-title-button').first().evaluate(n => { n.textContent = '서울시지역생활지원공식서비스'.repeat(8); });
  await layout('long-name-320');
  await page.reload(); await ready();
  await page.evaluate(() => { Storage.prototype.setItem = () => { throw Error('Storage unavailable'); }; });
  await page.locator('.service-save').first().click();
  assert.match(await page.locator('#serviceStorageStatus').innerText(), /저장하지 못했습니다/);
  checks.push('storage-denied-feedback');
  await page.goto(base + '/?item=P137#catalog');
  await page.locator('#catalogDetailBody [data-life-links] a').waitFor();
  await page.locator('#catalogDetailBody [data-life-links] a').click(); await ready();
  assert.match(page.url(), /problem=laundry/);
  assert(await page.locator('#serviceProblemContext').isVisible());
  checks.push('duvet-to-services');
  assert.deepEqual(errors, []);
  writeFileSync(`${out}/report.json`, JSON.stringify({ checkedOn: new Date().toISOString(), checks, errors, scope: 'Local UI, not external app installation or booking verification' }, null, 2));
  console.log(JSON.stringify({ passed: checks.length, errors }));
} finally { await browser.close(); }
